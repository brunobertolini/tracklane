/**
 * Everything a conversion API needs beyond the event itself: who the person
 * is, when it happened, and where it was observed.
 *
 * None of this is "what happened", which is why it does not travel in the
 * event data: putting it there would leak identity into the pass-through
 * event params of the vendors that forward the payload as-is.
 */
export interface EventContext {
  /** The person's identity, the server-side counterpart to `identify()` on the browser. */
  user?: UserData;
  /**
   * The request's raw `Cookie` header, or an already-parsed map.
   *
   * These are cookies the vendors' own browser tags set. This library never
   * writes one. On the server each adapter reads the cookies belonging to
   * its own vendor: Meta forwards its value as-is, Google's holds several
   * things at once and has to be opened. That knowledge lives in the
   * adapters; the core only splits `name=value; name=value` into pairs.
   *
   * **It splits, it does not interpret.** Values are handed over exactly as
   * they appear, with no percent-decoding. The cookies these vendors set do
   * not need it; a host reading some other cookie should decode it itself.
   */
  cookies?: string | Record<string, string> | null;
  /** Ties this send to a browser hit. Never invented by the library. */
  dedupId?: string;
  /**
   * When the conversion actually happened. Defaults to now.
   *
   * A webhook arrives after the fact and LinkedIn rejects conversions older
   * than 90 days, so reporting "now" for everything would quietly distort
   * attribution.
   */
  timestamp?: number | Date;
  /** Overrides the factory default. Meta requires it on every event. */
  source?: ActionSource;
  /** The page the conversion happened on. Meta's Conversions API reads it as `event_source_url`. */
  url?: string;
  /** The visitor's IP. Meta's Conversions API reads it as one of the identifiers in `user_data`. */
  ip?: string;
  /** The visitor's user agent. Meta's Conversions API reads it alongside `ip`. */
  userAgent?: string;
  /**
   * What is known *about* the person: GA4 user properties, PostHog `$set`.
   *
   * A trait set to `null` means "no longer known". PostHog receives it in
   * `$unset`. GA4 leaves it out and reports that it did, because clearing a
   * user property through the Measurement Protocol is not yet verified.
   */
  traits?: Record<string, unknown>;
  /**
   * When the traits were true, if not when the event happened. Same units as
   * `timestamp`. GA4 stamps each user property with it; vendors with no slot
   * ignore it.
   */
  traitsAt?: number | Date;
  /**
   * Your own stable id for a visitor nobody has identified yet. Never
   * generated by the library.
   *
   * PostHog uses it as `distinct_id` when there is no `user.userId`, ahead of
   * its cookie, and `identify` merges it into the user. It must be the id the
   * earlier PostHog events were captured under, or it merges nothing.
   */
  anonymousId?: string;
  /** Cancels the vendor requests. An aborted send is reported as an error. */
  signal?: AbortSignal;
  /**
   * Travels inside the event, for the vendors that document such a field.
   * Today that is GA4's Measurement Protocol, and it reads two of the
   * signals; the others have no slot and ignore it.
   */
  consent?: ConsentState;
}

/** The context an adapter receives, with the ambiguity resolved. */
export interface ResolvedContext extends Omit<EventContext, 'cookies' | 'timestamp' | 'traitsAt'> {
  /** The request's cookies, already split into a `name → value` map. */
  cookies: Record<string, string>;
  /** Epoch milliseconds. Adapters convert to their vendor's spelling. */
  timestamp: number;
  /** Epoch milliseconds, when the host gave one. */
  traitsAt?: number;
}

/**
 * The context {@link ServerTracking.identify} takes: the same one `track`
 * takes, with the person's id required.
 */
export interface IdentifyContext extends EventContext {
  /** Who the person is. `userId` is required: identifying nobody is not a call. */
  user: UserData & { userId: string };
}

/**
 * A destination for server events.
 *
 * `track` may throw, on a non-2xx or where a vendor documents a
 * precondition the event cannot meet. The dispatcher isolates and reports
 * it, so adapters stay honest and loud.
 *
 * `report` is for a caveat about a request that already succeeded. It does
 * not throw: by then the send happened, and throwing would tell a host's
 * retry logic to resend a delivered conversion.
 */
export interface ServerProvider<Target = string> {
  /** The vendor's fixed name. Registering one twice is an error. */
  name: string;
  /** What happens to a canonical event this vendor has no binding for. */
  default: ProviderDefault;
  /** How this vendor spells each canonical event. */
  events?: Record<string, EventBinding<Target>>;
  /** Sends one event to this vendor's conversion API. May throw, or call `report` for a caveat. */
  track(
    name: Target,
    data: EventData,
    context: ResolvedContext,
    report: (message: string) => void,
  ): Promise<void>;
  /**
   * Tells this vendor who the person is, with no event. Absent where the
   * vendor keeps no person of its own. May throw, or call `report` for a caveat.
   */
  identify?(context: ResolvedContext, report: (message: string) => void): Promise<void>;
}

/** Options accepted by {@link createTracking}. */
export interface ServerTrackingOptions {
  /** The vendors to send every event to. Registering the same `name` twice throws. */
  providers: readonly ServerProvider[];
  /**
   * The one diagnostic channel. Without it the library is silent, exactly as
   * a hand-written vendor call is.
   * Unmapped events on an `ignore` provider report warnings; explicit `null`
   * exclusions stay silent. Attach a reporter in development to catch omissions.
   */
  onError?: (error: TrackingError) => void;
}

/** What {@link createTracking} returns. */
export interface ServerTracking {
  /**
   * Sends one event to every configured conversion API.
   *
   * Resolves once every provider has settled and never rejects: one vendor
   * being down is not the caller's failure to handle. Awaiting is about the
   * request surviving a serverless runtime, not about delivery being
   * guaranteed.
   */
  track(name: string, data?: EventData, context?: EventContext): Promise<void>;
  /**
   * Tells every vendor that keeps a person who this one is, with no event:
   * PostHog's `$identify` and a GA4 request with user properties only.
   * Vendors that keep no person receive nothing.
   *
   * A merge happens only when `anonymousId` is given. PostHog merges are
   * irreversible, so pass it only when you know that visitor is this person.
   * Resolves once every provider has settled and never rejects.
   */
  identify(context: IdentifyContext): Promise<void>;
}

/** `name=value; name=value`, the shape of a `Cookie` header. */
function parseCookies(
  cookies: string | Record<string, string> | null | undefined,
): Record<string, string> {
  if (!cookies) return {};
  if (typeof cookies !== 'string') return cookies;

  const parsed: Record<string, string> = {};

  for (const pair of cookies.split(';')) {
    const separator = pair.indexOf('=');
    if (separator < 1) continue;

    const name = pair.slice(0, separator).trim();
    // Cookie values may contain `=`, so only the first one separates.
    if (name) parsed[name] = pair.slice(separator + 1).trim();
  }

  return parsed;
}

function toEpoch(value: number | Date): number {
  return value instanceof Date ? value.getTime() : value;
}

function resolveContext(context: EventContext): ResolvedContext {
  const { cookies, timestamp, traitsAt, ...rest } = context;

  return {
    ...rest,
    cookies: parseCookies(cookies),
    timestamp: timestamp === undefined ? Date.now() : toEpoch(timestamp),
    ...(traitsAt === undefined ? {} : { traitsAt: toEpoch(traitsAt) }),
  };
}

/**
 * Creates the server tracking surface.
 *
 * Nothing is held between calls: a server instance is shared by every
 * request, so a retained identity would attach one visitor to another
 * visitor's conversion. Identity travels with each call, `identify`
 * included, which is also what every conversion API expects.
 *
 * There is no `consent` call either. Consent commands are properties of a
 * vendor's on-page tag, and a server request has no tag. The one vendor that
 * accepts consent server-side reads it from the context.
 *
 * @param options - The providers to send to, and an optional error channel.
 * @returns The `track` and `identify` calls.
 *
 * @example
 * ```ts
 * import { createTracking, ga4 } from 'tracklane/server';
 *
 * const { track } = createTracking({
 *   providers: [ga4({ measurementId: 'G-XXXXXXX', apiSecret })],
 * });
 *
 * await track('purchase', order, { cookies: request.headers.get('cookie') });
 * ```
 */
export function createTracking(options: ServerTrackingOptions): ServerTracking {
  const { providers } = options;
  assertUniqueProviders(providers);

  const report = makeReporter(options.onError);

  // One provider's send, isolated: a throw becomes an error report and a
  // caveat becomes a warning, and neither reaches the caller.
  const settle = async (
    provider: ServerProvider,
    event: string,
    send: (warn: (message: string) => void) => Promise<void>,
  ): Promise<void> => {
    try {
      await send((message) => {
        report({ provider: provider.name, event, severity: 'warning', message });
      });
    } catch (cause) {
      report({
        provider: provider.name,
        event,
        severity: 'error',
        message: messageOf(cause),
        cause,
      });
    }
  };

  return {
    async track(name, data = {}, context = {}) {
      const resolved = resolveContext(context);

      await Promise.all(
        providers.map(async (provider) => {
          const target = resolveEvent(provider, name, (message) => {
            report({ provider: provider.name, event: name, severity: 'warning', message });
          });
          if (target === undefined) return;

          await settle(provider, name, (warn) => provider.track(target, data, resolved, warn));
        }),
      );
    },

    async identify(context) {
      const resolved = resolveContext(context);

      await Promise.all(
        providers.map((provider) => {
          const identify = provider.identify?.bind(provider);
          if (!identify) return undefined;

          return settle(provider, 'identify', (warn) => identify(resolved, warn));
        }),
      );
    },
  };
}
